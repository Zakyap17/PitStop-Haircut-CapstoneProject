CREATE TABLE IF NOT EXISTS pengguna (
  id_pengguna bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_lengkap varchar(160) NOT NULL,
  email varchar(255) NOT NULL UNIQUE,
  password_hash text NOT NULL,
  role varchar(24) NOT NULL CHECK (role IN ('owner','admin','capster')),
  status_aktif boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS capster (
  id_capster bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna bigint UNIQUE REFERENCES pengguna(id_pengguna),
  nama_capster varchar(160) NOT NULL,
  spesialisasi varchar(255),
  foto text,
  status_aktif boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS profil_usaha (
  id_profil bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna bigint UNIQUE REFERENCES pengguna(id_pengguna),
  nama_usaha varchar(160) NOT NULL,
  alamat text,
  no_kontak varchar(64),
  jam_operasional text
);

CREATE TABLE IF NOT EXISTS customer (
  id_customer bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_customer varchar(160) NOT NULL,
  no_whatsapp varchar(32) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS customer_whatsapp_idx ON customer(no_whatsapp);

CREATE TABLE IF NOT EXISTS otp_riwayat (
  id_otp bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_customer bigint NOT NULL REFERENCES customer(id_customer),
  kode_otp_hash text NOT NULL,
  waktu_kadaluarsa timestamptz NOT NULL,
  status_pakai boolean NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS layanan (
  id_layanan bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_layanan varchar(160) NOT NULL,
  deskripsi text,
  harga numeric(14,2) NOT NULL CHECK (harga >= 0),
  durasi_menit integer NOT NULL CHECK (durasi_menit > 0),
  status_aktif boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS booking (
  id_booking bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_booking varchar(64) NOT NULL UNIQUE,
  id_customer bigint NOT NULL REFERENCES customer(id_customer),
  id_capster bigint REFERENCES capster(id_capster),
  tipe_booking varchar(32) NOT NULL DEFAULT 'online',
  tanggal_booking date NOT NULL,
  jam_mulai time NOT NULL,
  jam_selesai time NOT NULL,
  status_booking varchar(48) NOT NULL DEFAULT 'menunggu_konfirmasi',
  total_harga numeric(14,2) NOT NULL DEFAULT 0 CHECK (total_harga >= 0),
  nominal_dp numeric(14,2) NOT NULL DEFAULT 0 CHECK (nominal_dp >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  alasan_batal text,
  CHECK (jam_selesai > jam_mulai)
);
CREATE INDEX IF NOT EXISTS booking_date_capster_idx ON booking(tanggal_booking,id_capster,jam_mulai);

CREATE TABLE IF NOT EXISTS booking_layanan (
  id_detail bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_booking bigint NOT NULL REFERENCES booking(id_booking) ON DELETE CASCADE,
  id_layanan bigint NOT NULL REFERENCES layanan(id_layanan),
  harga_satuan numeric(14,2) NOT NULL CHECK (harga_satuan >= 0),
  subtotal numeric(14,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE IF NOT EXISTS jadwal_capster (
  id_jadwal bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_capster bigint NOT NULL REFERENCES capster(id_capster),
  tanggal date NOT NULL,
  jam_mulai time NOT NULL,
  jam_selesai time NOT NULL,
  status_slot varchar(32) NOT NULL,
  CHECK (jam_selesai > jam_mulai)
);

CREATE TABLE IF NOT EXISTS riwayat_layanan (
  id_riwayat bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_booking bigint REFERENCES booking(id_booking),
  id_capster bigint NOT NULL REFERENCES capster(id_capster),
  status_layanan varchar(48) NOT NULL,
  waktu_status timestamptz NOT NULL DEFAULT now(),
  catatan text
);

CREATE TABLE IF NOT EXISTS antrean_kosong (
  id_antrean bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_booking bigint REFERENCES booking(id_booking),
  id_capster bigint NOT NULL REFERENCES capster(id_capster),
  tanggal date NOT NULL,
  jam_mulai time NOT NULL,
  jam_selesai time NOT NULL,
  status_antrean varchar(32) NOT NULL
);

CREATE TABLE IF NOT EXISTS pembayaran (
  id_pembayaran bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_booking bigint NOT NULL REFERENCES booking(id_booking),
  jenis_pembayaran varchar(32) NOT NULL,
  metode_pembayaran varchar(48) NOT NULL,
  nominal numeric(14,2) NOT NULL CHECK (nominal >= 0),
  status_pembayaran varchar(32) NOT NULL,
  ref_gateway varchar(255),
  waktu_bayar timestamptz
);

CREATE TABLE IF NOT EXISTS transaksi (
  id_transaksi bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode_transaksi varchar(64) NOT NULL UNIQUE,
  jenis_transaksi varchar(24) NOT NULL CHECK (jenis_transaksi IN ('booking','walk-in')),
  id_booking bigint UNIQUE REFERENCES booking(id_booking),
  id_customer bigint REFERENCES customer(id_customer),
  id_capster bigint REFERENCES capster(id_capster),
  id_pengguna bigint REFERENCES pengguna(id_pengguna),
  total_tagihan numeric(14,2) NOT NULL CHECK (total_tagihan >= 0),
  total_dibayar numeric(14,2) NOT NULL DEFAULT 0 CHECK (total_dibayar >= 0),
  status_transaksi varchar(32) NOT NULL DEFAULT 'belum_lunas',
  status_layanan varchar(32) NOT NULL DEFAULT 'menunggu',
  metode_pembayaran varchar(48),
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((jenis_transaksi = 'booking' AND id_booking IS NOT NULL) OR (jenis_transaksi = 'walk-in' AND id_booking IS NULL))
);
CREATE INDEX IF NOT EXISTS transaksi_created_at_idx ON transaksi(created_at DESC);
CREATE TABLE IF NOT EXISTS transaksi_layanan (
  id_detail bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_transaksi bigint NOT NULL REFERENCES transaksi(id_transaksi) ON DELETE CASCADE,
  id_layanan bigint REFERENCES layanan(id_layanan),
  nama_layanan_snapshot varchar(160) NOT NULL,
  harga_satuan numeric(14,2) NOT NULL CHECK (harga_satuan >= 0),
  subtotal numeric(14,2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE IF NOT EXISTS invoice (
  id_invoice bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_booking bigint UNIQUE REFERENCES booking(id_booking),
  id_transaksi bigint UNIQUE REFERENCES transaksi(id_transaksi),
  nomor_invoice varchar(64) NOT NULL UNIQUE,
  tanggal_terbit date NOT NULL,
  total_tagihan numeric(14,2) NOT NULL CHECK (total_tagihan >= 0),
  file_pdf text,
  CHECK (id_booking IS NOT NULL OR id_transaksi IS NOT NULL)
);
ALTER TABLE invoice ALTER COLUMN id_booking DROP NOT NULL;
ALTER TABLE invoice ADD COLUMN IF NOT EXISTS id_transaksi bigint UNIQUE REFERENCES transaksi(id_transaksi);
ALTER TABLE riwayat_layanan ADD COLUMN IF NOT EXISTS id_transaksi bigint REFERENCES transaksi(id_transaksi);
ALTER TABLE riwayat_layanan ALTER COLUMN id_booking DROP NOT NULL;
ALTER TABLE transaksi ADD COLUMN IF NOT EXISTS status_layanan varchar(32) NOT NULL DEFAULT 'menunggu';

CREATE TABLE IF NOT EXISTS notifikasi_whatsapp (
  id_notifikasi bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_booking bigint NOT NULL REFERENCES booking(id_booking),
  no_tujuan varchar(32) NOT NULL,
  jenis_pesan varchar(48) NOT NULL,
  status_kirim varchar(32) NOT NULL,
  waktu_kirim timestamptz
);

CREATE TABLE IF NOT EXISTS pengeluaran (
  id_pengeluaran bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna bigint NOT NULL REFERENCES pengguna(id_pengguna),
  kategori varchar(120) NOT NULL,
  deskripsi text,
  nominal numeric(14,2) NOT NULL CHECK (nominal > 0),
  tanggal_pengeluaran date NOT NULL
);

CREATE TABLE IF NOT EXISTS galeri (
  id_galeri bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna bigint NOT NULL REFERENCES pengguna(id_pengguna),
  judul varchar(160) NOT NULL,
  file_gambar text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS pengaturan_dp (
  id_pengaturan bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna bigint NOT NULL REFERENCES pengguna(id_pengguna),
  persentase_dp numeric(5,2) NOT NULL CHECK (persentase_dp > 0 AND persentase_dp <= 100),
  berlaku_sejak date NOT NULL
);

CREATE TABLE IF NOT EXISTS jejak_audit (
  id_log bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna bigint REFERENCES pengguna(id_pengguna),
  waktu timestamptz NOT NULL DEFAULT now(),
  aksi varchar(120) NOT NULL,
  jenis_objek varchar(80) NOT NULL,
  id_objek bigint
);

CREATE TABLE IF NOT EXISTS laporan (
  id_laporan bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pengguna bigint NOT NULL REFERENCES pengguna(id_pengguna),
  jenis_laporan varchar(80) NOT NULL,
  periode_mulai date NOT NULL,
  periode_selesai date NOT NULL,
  format_ekspor varchar(16) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
